package day18;

public class PrintInJava {

    static void main() {

        byte b1 = 45;
        short s1 = 50;
        int i1 = 55;
        long l1 = 918860418225L;

        System.out.println(b1); //45
        System.out.println(s1); //50
        System.out.println(i1); //55
        System.out.println(l1); //918860418225

    }
}
