package day21;

public class WhileLoopConceptImplementation {
    static void main() {
        System.out.println("========Larry=====");

        int i = 1;
        while (i <= 100) {
            System.out.println("Larry");
            i++;
        }

        System.out.println("========1 to 10 =====");

        int j = 1;
        while (j <= 10) {
            System.out.println(j);
            j++;
        }

        System.out.println("========10 to 1 =====");

        int k = 10;
        while (k > 0) {
            System.out.println(k);//
            k--;
        }

        System.out.println("========print table of 2 =====");

        int l = 1;
        while (l<=10)
        {
            System.out.println(2*l);
            l++;
        }
    }
}
