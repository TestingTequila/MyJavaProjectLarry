package day21;

public class ForLoopConceptImplementation {
    static void main() {
        System.out.println("========Larry=====");


        for (int i = 1;i <= 20;i++) {
            System.out.println("Larry" + i);

        }

        System.out.println("========1 to 10 =====");
        for (int j = 1;j <= 10;j++) {
            System.out.println(j);

        }

        System.out.println("========10 to 1 =====");

        for (int k = 10;k > 0;k--) {
            System.out.println(k);
        }

        System.out.println("========print table of 2 =====");


        for (int l = 1;l<=10;l++)
        {
            System.out.println(3*l);
        }
    }
}
